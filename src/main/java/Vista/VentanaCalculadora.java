    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        try {

    double numero1 = Double.parseDouble(txtNumero1.getText());

    double resultado;

    if (tipoOperacion.equals("suma")
            || tipoOperacion.equals("resta")
            || tipoOperacion.equals("multiplicacion")
            || tipoOperacion.equals("division")) {

        double numero2 = Double.parseDouble(txtNumero2.getText());

        resultado = controlador.realizarOperacion(
                tipoOperacion,
                numero1,
                numero2
        );

    } else {

        resultado = controlador.realizarOperacion(
                tipoOperacion,
                numero1
        );
    }

    txtResultado.setText(String.valueOf(resultado));

} catch (NumberFormatException e) {

    txtResultado.setText("Ingrese números válidos");

} catch (ArithmeticException e) {

    txtResultado.setText(e.getMessage());

} catch (IllegalArgumentException e) {

    txtResultado.setText(e.getMessage());
}
    }//GEN-LAST:event_btnCalcularActionPerformed

